/*
 * sw/tests/t_vtrace.S
 *
 * Self-checking test for Stage 2 Custom-1 VTRACE hardware accelerator.
 * Verifies:
 *   - VSET (funct3=000, funct7=0..7): sets ray state fields 0..7
 *   - VTRACE (funct3=001, funct7=0): executes DDA traversal up to max_steps
 *   - VGET (funct3=010, funct7=0..1): field 0 = hit cell, field 1 = t hit
 *
 * Verification Strategy:
 *   1. Scalar initializes full 131,072-byte world memory in BRAM (0x20000000)
 *      with air (0x00), then loads small sparse non-zero blocks.
 *   2. Sets MMIO registers WIN_ORIGIN = 0 (0x5000003C) and SLOT_VALID = 0xFFFF (0x50000038).
 *   3. Evaluates 16 deterministic reference vectors covering:
 *      - Misses and hits
 *      - All six exit directions (-X, +X, -Y, +Y, -Z, +Z)
 *      - Step-cap exhaustion (max_steps reached in empty space)
 *      - All 8 ray step sign combinations
 *      - Multi-axis diagonal traversals
 *   4. Asserts hardware results against genuine C-reference constants
 *      generated by sw/ref/vtrace_vectors.c calling game/src/trace.c:vtrace_ref().
 *   5. Stage 2 multi-lane check: exercises 8-lane SIMD execution under mask,
 *      verifying that active lanes produce expected results and inactive lanes
 *      have memory stores suppressed.
 *
 * Failure Codes:
 *   Vector loop:
 *     Vector i res mismatch:  i * 4 + 1
 *     Vector i cell mismatch: i * 4 + 2
 *     Vector i t mismatch:    i * 4 + 3
 *   Stage 2 SIMD multi-lane checks:
 *     100..107: Lane 0..7 res or canary suppression mismatch
 *     110..117: Lane 0..7 cell or canary suppression mismatch
 *     120..127: Lane 0..7 t or canary suppression mismatch
 */

    .include "sw/tests/test.inc"

    .globl main
    .section .text
main:
    # 1. Switch to scalar mask 1
    SCALAR

    # 2. Configure world memory window registers in MMIO (base 0x50000000)
    li      s0, 0x50000000

    # WIN_ORIGIN = 0 (MMIO_WIN_ORIGIN = 0x3C)
    sw      zero, 0x3C(s0)

    # SLOT_VALID = 0xFFFF (all 16 slots valid, MMIO_SLOT_VALID = 0x38)
    li      t0, 0xFFFF
    sw      t0, 0x38(s0)

    # 3. Scalar-initialize full 131,072-byte world memory in BRAM (0x20000000)
    # Clear all 32,768 32-bit words (131072 bytes) to 0 (air)
    li      t1, 0x20000000                  # World window start
    li      t2, 0x20020000                  # World window end (0x20000000 + 131072)
.Lclear_world_loop:
    sw      zero, 0(t1)
    addi    t1, t1, 4
    bltu    t1, t2, .Lclear_world_loop

    # Populate small sparse non-zero blocks from vtrace_sparse_world
    la      t0, vtrace_sparse_world
    la      t1, vtrace_sparse_world_count
    lw      t1, 0(t1)                       # sparse block count
    li      t2, 0x20000000                  # World window base
.Lpopulate_sparse_loop:
    beqz    t1, .Lpopulate_sparse_done
    lw      t3, 0(t0)                       # byte offset in world window
    lw      t4, 4(t0)                       # block type (low 4 bits)
    add     t5, t2, t3
    sb      t4, 0(t5)                       # store voxel byte
    addi    t0, t0, 8
    addi    t1, t1, -1
    j       .Lpopulate_sparse_loop
.Lpopulate_sparse_done:

    # 4. Iterate over test vectors in scalar mode
    la      s1, vtrace_test_count
    lw      s2, 0(s1)                       # total test count (16)
    la      s3, vtrace_vectors              # vector pointer
    li      s4, 0                           # test index (0-based)

.Lvector_loop:
    beq     s4, s2, .Lscalar_vectors_done

    # Load ray fields f0..f7 into registers and issue VSET 0..7
    # VSET field, reg: .insn r 0x2B, 0, field, x0, reg, x0
    lw      t0, 0(s3)
    .insn r 0x2B, 0, 0, x0, t0, x0          # VSET 0, start cell packed

    lw      t0, 4(s3)
    .insn r 0x2B, 0, 1, x0, t0, x0          # VSET 1, tMax.x

    lw      t0, 8(s3)
    .insn r 0x2B, 0, 2, x0, t0, x0          # VSET 2, tMax.y

    lw      t0, 12(s3)
    .insn r 0x2B, 0, 3, x0, t0, x0          # VSET 3, tMax.z

    lw      t0, 16(s3)
    .insn r 0x2B, 0, 4, x0, t0, x0          # VSET 4, tDelta.x

    lw      t0, 20(s3)
    .insn r 0x2B, 0, 5, x0, t0, x0          # VSET 5, tDelta.y

    lw      t0, 24(s3)
    .insn r 0x2B, 0, 6, x0, t0, x0          # VSET 6, tDelta.z

    lw      t0, 28(s3)
    .insn r 0x2B, 0, 7, x0, t0, x0          # VSET 7, signs

    # Execute VTRACE with max_steps
    # VTRACE rd, rs1: .insn r 0x2B, 1, 0, rd, rs1, x0
    lw      a1, 32(s3)                      # max_steps
    .insn r 0x2B, 1, 0, a0, a1, x0          # VTRACE a0, a1 (res in a0)

    # Read VGET field 0 (cell) and field 1 (t)
    # VGET rd, field: .insn r 0x2B, 2, field, rd, x0, x0
    .insn r 0x2B, 2, 0, a2, x0, x0          # VGET a2, field 0 (cell)
    .insn r 0x2B, 2, 1, a3, x0, x0          # VGET a3, field 1 (t)

    # Compare res (low 16 bits): mask via slli/srli (avoids 12-bit andi overflow)
    slli    a0, a0, 16
    srli    a0, a0, 16
    lw      t0, 36(s3)                      # expected res
    slli    t0, t0, 16
    srli    t0, t0, 16

    # Lead Decision #6: On misses (hit == 0), face axis, face sign, hit_cell,
    # and t_hit are UNDEFINED in hardware. Assert hit == 0 and step count only.
    # Full result/VGET comparisons are performed only on actual hits.
    andi    t1, t0, 1                       # test expected hit bit
    bnez    t1, .Lverify_full_hit

    # ---- Miss verification ----
    # 1. Assert actual hit bit is 0
    andi    t2, a0, 1
    bnez    t2, .Lfail_res

    # 2. Assert step count matches (bits 15:8)
    srli    t2, a0, 8
    srli    t3, t0, 8
    bne     t2, t3, .Lfail_res

    # Face, sign, cell, and t are undefined on misses; advance to next vector
    j       .Lnext_vector

.Lverify_full_hit:
    # ---- Hit verification ----
    # 1. Assert full 16-bit res matches
    bne     a0, t0, .Lfail_res

    # 2. Assert hit cell matches expected cell
    lw      t0, 40(s3)                      # expected cell
    bne     a2, t0, .Lfail_cell

    # 3. Assert hit t matches expected t
    lw      t0, 44(s3)                      # expected t
    bne     a3, t0, .Lfail_t

    j       .Lnext_vector

.Lfail_res:
    SCALAR
    slli    a0, s4, 2
    addi    a0, a0, 1
    j       .Lbench_fail

.Lfail_cell:
    SCALAR
    slli    a0, s4, 2
    addi    a0, a0, 2
    j       .Lbench_fail

.Lfail_t:
    SCALAR
    slli    a0, s4, 2
    addi    a0, a0, 3
    j       .Lbench_fail
.Lnext_vector:
    addi    s3, s3, 48                      # 12 words per vector (stride = 48 bytes)
    addi    s4, s4, 1
    j       .Lvector_loop

.Lscalar_vectors_done:

#if defined(KC_STAGE) && (KC_STAGE >= 2)
    # 5. Stage 2 SIMD multi-lane verification under active mask 0x55.
    # Active lanes:   0, 2, 4, 6 (test vectors 0, 2, 4, 6)
    # Inactive lanes: 1, 3, 5, 7 (stores must be suppressed, canary preserved)

    # Clear scratch buffer with canary 0xCAFEBABE in scalar mode
    la      t0, lane_out_res
    la      t1, lane_out_cell
    la      t2, lane_out_t
    li      t3, 8                           # 8 lanes
    li      t4, 0xCAFEBABE                  # canary
.Lcanary_loop:
    sw      t4, 0(t0)
    sw      t4, 0(t1)
    sw      t4, 0(t2)
    addi    t0, t0, 4
    addi    t1, t1, 4
    addi    t2, t2, 4
    addi    t3, t3, -1
    bnez    t3, .Lcanary_loop

    # Activate all lanes to configure per-lane ray parameters from vtrace_vectors
    .insn r 0x0B, 7, 0, x0, x0, x0          # MASKALL
    .insn r 0x0B, 0, 0, a0, x0, x0          # LANEID a0 (0..7)

    # Compute vector pointer for this lane: map lanes 0..7 to vectors 8..15 (actual hits)
    # vector_idx = lane + 8; offset = vector_idx * 48
    addi    a3, a0, 8
    slli    a1, a3, 5                       # vector_idx * 32
    slli    a2, a3, 4                       # vector_idx * 16
    add     a1, a1, a2                      # vector_idx * 48
    la      a2, vtrace_vectors
    add     a2, a2, a1                      # &vtrace_vectors[vector_idx]

    # Issue per-lane VSET 0..7
    lw      t0, 0(a2)
    .insn r 0x2B, 0, 0, x0, t0, x0          # VSET 0
    lw      t0, 4(a2)
    .insn r 0x2B, 0, 1, x0, t0, x0          # VSET 1
    lw      t0, 8(a2)
    .insn r 0x2B, 0, 2, x0, t0, x0          # VSET 2
    lw      t0, 12(a2)
    .insn r 0x2B, 0, 3, x0, t0, x0          # VSET 3
    lw      t0, 16(a2)
    .insn r 0x2B, 0, 4, x0, t0, x0          # VSET 4
    lw      t0, 20(a2)
    .insn r 0x2B, 0, 5, x0, t0, x0          # VSET 5
    lw      t0, 24(a2)
    .insn r 0x2B, 0, 6, x0, t0, x0          # VSET 6
    lw      t0, 28(a2)
    .insn r 0x2B, 0, 7, x0, t0, x0          # VSET 7

    # Load max_steps for this lane
    lw      a1, 32(a2)

    # Set mask to 0x55 (lanes 0, 2, 4, 6 active)
    li      t0, 0x55
    .insn r 0x0B, 6, 0, x0, t0, x0          # MASKSET 0x55

    # Pre-fill registers with canary before custom instruction execution
    li      a4, 0xCAFEBABE
    li      a5, 0xCAFEBABE
    li      a6, 0xCAFEBABE

    # Execute VTRACE across active lanes
    .insn r 0x2B, 1, 0, a4, a1, x0          # VTRACE a4, a1

    # Read VGET across active lanes
    .insn r 0x2B, 2, 0, a5, x0, x0          # VGET a5, 0 (cell)
    .insn r 0x2B, 2, 1, a6, x0, x0          # VGET a6, 1 (t)

    # Per-lane store to scratch buffer:
    # Active lanes store their results; inactive lanes MUST BE SUPPRESSED!
    slli    a2, a0, 2                       # lane * 4
    la      t0, lane_out_res
    add     t0, t0, a2
    sw      a4, 0(t0)

    la      t1, lane_out_cell
    add     t1, t1, a2
    sw      a5, 0(t1)

    la      t2, lane_out_t
    add     t2, t2, a2
    sw      a6, 0(t2)

    # Return to scalar mask 1
    SCALAR

    # Validate results in scalar mode
    li      s6, 0xCAFEBABE                  # canary
    la      s3, vtrace_vectors
    la      t0, lane_out_res
    la      t1, lane_out_cell
    la      t2, lane_out_t

    # ---- Lane 0: Active (matches vector 8, offset 8 * 48 = 384) ----
    lw      a0, 0(t0)
    slli    a0, a0, 16
    srli    a0, a0, 16
    lw      t3, 420(s3)                     # 384 + 36 = 420 (vector 8 res)
    slli    t3, t3, 16
    srli    t3, t3, 16
    EXPECT_REG a0, t3, 100

    lw      a0, 0(t1)
    lw      t3, 424(s3)                     # 384 + 40 = 424 (vector 8 cell)
    EXPECT_REG a0, t3, 110

    lw      a0, 0(t2)
    lw      t3, 428(s3)                     # 384 + 44 = 428 (vector 8 t)
    EXPECT_REG a0, t3, 120

    # ---- Lane 1: Inactive (store suppressed, must remain canary) ----
    lw      a0, 4(t0)
    EXPECT_REG a0, s6, 101
    lw      a0, 4(t1)
    EXPECT_REG a0, s6, 111
    lw      a0, 4(t2)
    EXPECT_REG a0, s6, 121

    # ---- Lane 2: Active (matches vector 10, offset 10 * 48 = 480) ----
    lw      a0, 8(t0)
    slli    a0, a0, 16
    srli    a0, a0, 16
    lw      t3, 516(s3)                     # 480 + 36 = 516 (vector 10 res)
    slli    t3, t3, 16
    srli    t3, t3, 16
    EXPECT_REG a0, t3, 102

    lw      a0, 8(t1)
    lw      t3, 520(s3)                     # 480 + 40 = 520 (vector 10 cell)
    EXPECT_REG a0, t3, 112

    lw      a0, 8(t2)
    lw      t3, 524(s3)                     # 480 + 44 = 524 (vector 10 t)
    EXPECT_REG a0, t3, 122

    # ---- Lane 3: Inactive (store suppressed, must remain canary) ----
    lw      a0, 12(t0)
    EXPECT_REG a0, s6, 103
    lw      a0, 12(t1)
    EXPECT_REG a0, s6, 113
    lw      a0, 12(t2)
    EXPECT_REG a0, s6, 123

    # ---- Lane 4: Active (matches vector 12, offset 12 * 48 = 576) ----
    lw      a0, 16(t0)
    slli    a0, a0, 16
    srli    a0, a0, 16
    lw      t3, 612(s3)                     # 576 + 36 = 612 (vector 12 res)
    slli    t3, t3, 16
    srli    t3, t3, 16
    EXPECT_REG a0, t3, 104

    lw      a0, 16(t1)
    lw      t3, 616(s3)                     # 576 + 40 = 616 (vector 12 cell)
    EXPECT_REG a0, t3, 114

    lw      a0, 16(t2)
    lw      t3, 620(s3)                     # 576 + 44 = 620 (vector 12 t)
    EXPECT_REG a0, t3, 124

    # ---- Lane 5: Inactive (store suppressed, must remain canary) ----
    lw      a0, 20(t0)
    EXPECT_REG a0, s6, 105
    lw      a0, 20(t1)
    EXPECT_REG a0, s6, 115
    lw      a0, 20(t2)
    EXPECT_REG a0, s6, 125

    # ---- Lane 6: Active (matches vector 14, offset 14 * 48 = 672) ----
    lw      a0, 24(t0)
    slli    a0, a0, 16
    srli    a0, a0, 16
    lw      t3, 708(s3)                     # 672 + 36 = 708 (vector 14 res)
    slli    t3, t3, 16
    srli    t3, t3, 16
    EXPECT_REG a0, t3, 106

    lw      a0, 24(t1)
    lw      t3, 712(s3)                     # 672 + 40 = 712 (vector 14 cell)
    EXPECT_REG a0, t3, 116

    lw      a0, 24(t2)
    lw      t3, 716(s3)                     # 672 + 44 = 716 (vector 14 t)
    EXPECT_REG a0, t3, 126

    # ---- Lane 7: Inactive (store suppressed, must remain canary) ----
    lw      a0, 28(t0)
    EXPECT_REG a0, s6, 107
    lw      a0, 28(t1)
    EXPECT_REG a0, s6, 117
    lw      a0, 28(t2)
    EXPECT_REG a0, s6, 127
#endif

    # All tests passed!
    PASS

    # Include expected reference vectors and sparse world data generated from C reference
    .include "sw/tests/t_vtrace_expected.inc"

    .section .bss
    .balign 4
lane_out_res:
    .space 32
lane_out_cell:
    .space 32
lane_out_t:
    .space 32
