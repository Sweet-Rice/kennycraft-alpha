/*
 * sw/tests/t_vtrace.S
 *
 * Self-checking test for Stage 2 Custom-1 VTRACE hardware accelerator.
 * Verifies:
 *   - VSET (funct3=000, funct7=0..7): sets ray state fields 0..7
 *   - VTRACE (funct3=001, funct7=0): executes DDA traversal up to max_steps
 *   - VGET (funct3=010, funct7=0..1): field 0 = hit cell, field 1 = t hit
 *
 * Verification Strategy:
 *   1. Scalar initializes full 131,072-byte world memory in BRAM (0x20000000)
 *      with air (0x00), then loads small sparse non-zero blocks.
 *   2. Sets MMIO registers WIN_ORIGIN = 0 (0x5000003C) and SLOT_VALID = 0xFFFF (0x50000038).
 *   3. Evaluates 16 deterministic reference vectors covering:
 *      - Misses and hits
 *      - All six exit directions (-X, +X, -Y, +Y, -Z, +Z)
 *      - Step-cap exhaustion (max_steps reached in empty space)
 *      - All 8 ray step sign combinations
 *      - Multi-axis diagonal traversals
 *   4. Asserts hardware results against genuine C-reference constants
 *      generated by sw/ref/vtrace_vectors.c calling game/src/trace.c:vtrace_ref().
 *   5. Stage 2 multi-lane checks (Tai_2 §2): under a mask, active lanes get
 *      the expected results while inactive lanes keep rd, VGET results and ray
 *      state; the step cap comes from the scalar lane's rs1[7:0]; a cap of 0,
 *      a cap of 256 and M = 0 write nothing.
 *
 * Failure Codes:
 *   Vector loop:
 *     Vector i res mismatch:  i * 4 + 1
 *     Vector i cell mismatch: i * 4 + 2
 *     Vector i t mismatch:    i * 4 + 3
 *   Stage 2 multi-lane checks (pass 1, M = 0xAA / pass 2, M = 0x55):
 *     100..107 / 130..137: Lane 0..7 res mismatch or canary overwritten
 *     110..117 / 140..147: Lane 0..7 cell mismatch or canary overwritten
 *     120..127 / 150..157: Lane 0..7 t mismatch or canary overwritten
 *   No-write VTRACE (a lane's rd or VGET result changed):
 *     160: cap 0, 161: cap 256, 162: M = 0
 */

    .include "sw/tests/test.inc"

    .globl main
    .section .text
main:
    # 1. Switch to scalar mask 1
    SCALAR

    # 2. Configure world memory window registers in MMIO (base 0x50000000)
    li      s0, 0x50000000

    # WIN_ORIGIN = 0 (MMIO_WIN_ORIGIN = 0x3C)
    sw      zero, 0x3C(s0)

    # SLOT_VALID = 0xFFFF (all 16 slots valid, MMIO_SLOT_VALID = 0x38)
    li      t0, 0xFFFF
    sw      t0, 0x38(s0)

    # 3. Scalar-initialize full 131,072-byte world memory in BRAM (0x20000000)
    # Clear all 32,768 32-bit words (131072 bytes) to 0 (air)
    li      t1, 0x20000000                  # World window start
    li      t2, 0x20020000                  # World window end (0x20000000 + 131072)
.Lclear_world_loop:
    sw      zero, 0(t1)
    addi    t1, t1, 4
    bltu    t1, t2, .Lclear_world_loop

    # Populate small sparse non-zero blocks from vtrace_sparse_world
    la      t0, vtrace_sparse_world
    la      t1, vtrace_sparse_world_count
    lw      t1, 0(t1)                       # sparse block count
    li      t2, 0x20000000                  # World window base
.Lpopulate_sparse_loop:
    beqz    t1, .Lpopulate_sparse_done
    lw      t3, 0(t0)                       # byte offset in world window
    lw      t4, 4(t0)                       # block type (low 4 bits)
    add     t5, t2, t3
    sb      t4, 0(t5)                       # store voxel byte
    addi    t0, t0, 8
    addi    t1, t1, -1
    j       .Lpopulate_sparse_loop
.Lpopulate_sparse_done:

    # 4. Iterate over test vectors in scalar mode
    la      s1, vtrace_test_count
    lw      s2, 0(s1)                       # total test count (16)
    la      s3, vtrace_vectors              # vector pointer
    li      s4, 0                           # test index (0-based)

.Lvector_loop:
    beq     s4, s2, .Lscalar_vectors_done

    # Load ray fields f0..f7 into registers and issue VSET 0..7
    # VSET field, reg: .insn r 0x2B, 0, field, x0, reg, x0
    lw      t0, 0(s3)
    .insn r 0x2B, 0, 0, x0, t0, x0          # VSET 0, start cell packed

    lw      t0, 4(s3)
    .insn r 0x2B, 0, 1, x0, t0, x0          # VSET 1, tMax.x

    lw      t0, 8(s3)
    .insn r 0x2B, 0, 2, x0, t0, x0          # VSET 2, tMax.y

    lw      t0, 12(s3)
    .insn r 0x2B, 0, 3, x0, t0, x0          # VSET 3, tMax.z

    lw      t0, 16(s3)
    .insn r 0x2B, 0, 4, x0, t0, x0          # VSET 4, tDelta.x

    lw      t0, 20(s3)
    .insn r 0x2B, 0, 5, x0, t0, x0          # VSET 5, tDelta.y

    lw      t0, 24(s3)
    .insn r 0x2B, 0, 6, x0, t0, x0          # VSET 6, tDelta.z

    lw      t0, 28(s3)
    .insn r 0x2B, 0, 7, x0, t0, x0          # VSET 7, signs

    # Execute VTRACE with max_steps
    # VTRACE rd, rs1: .insn r 0x2B, 1, 0, rd, rs1, x0
    lw      a1, 32(s3)                      # max_steps
    .insn r 0x2B, 1, 0, a0, a1, x0          # VTRACE a0, a1 (res in a0)

    # Read VGET field 0 (cell) and field 1 (t)
    # VGET rd, field: .insn r 0x2B, 2, field, rd, x0, x0
    .insn r 0x2B, 2, 0, a2, x0, x0          # VGET a2, field 0 (cell)
    .insn r 0x2B, 2, 1, a3, x0, x0          # VGET a3, field 1 (t)

    # Compare res (low 16 bits): mask via slli/srli (avoids 12-bit andi overflow)
    slli    a0, a0, 16
    srli    a0, a0, 16
    lw      t0, 36(s3)                      # expected res
    slli    t0, t0, 16
    srli    t0, t0, 16

    # Lead Decision #6: On misses (hit == 0), face axis, face sign, hit_cell,
    # and t_hit are UNDEFINED in hardware. Assert hit == 0 and step count only.
    # Full result/VGET comparisons are performed only on actual hits.
    andi    t1, t0, 1                       # test expected hit bit
    bnez    t1, .Lverify_full_hit

    # ---- Miss verification ----
    # 1. Assert actual hit bit is 0
    andi    t2, a0, 1
    bnez    t2, .Lfail_res

    # 2. Assert step count matches (bits 15:8)
    srli    t2, a0, 8
    srli    t3, t0, 8
    bne     t2, t3, .Lfail_res

    # Face, sign, cell, and t are undefined on misses; advance to next vector
    j       .Lnext_vector

.Lverify_full_hit:
    # ---- Hit verification ----
    # 1. Assert full 16-bit res matches
    bne     a0, t0, .Lfail_res

    # 2. Assert hit cell matches expected cell
    lw      t0, 40(s3)                      # expected cell
    bne     a2, t0, .Lfail_cell

    # 3. Assert hit t matches expected t
    lw      t0, 44(s3)                      # expected t
    bne     a3, t0, .Lfail_t

    j       .Lnext_vector

.Lfail_res:
    SCALAR
    slli    a0, s4, 2
    addi    a0, a0, 1
    j       .Lbench_fail

.Lfail_cell:
    SCALAR
    slli    a0, s4, 2
    addi    a0, a0, 2
    j       .Lbench_fail

.Lfail_t:
    SCALAR
    slli    a0, s4, 2
    addi    a0, a0, 3
    j       .Lbench_fail
.Lnext_vector:
    addi    s3, s3, 48                      # 12 words per vector (stride = 48 bytes)
    addi    s4, s4, 1
    j       .Lvector_loop

.Lscalar_vectors_done:

#if defined(KC_STAGE) && (KC_STAGE >= 2)
    # 5. Stage 2 multi-lane checks (Tai_2 §2, VTRACE and VGET rows).
    # Lane L traces vector L + 8 (all hits). Every lane gets its ray state and
    # canary registers under MASKALL, so inactive lanes hold values that a
    # masked VTRACE or VGET must leave alone.
    #   Pass 1, M = 0xAA: lanes 1, 3, 5, 7 trace into a4..a6. Only lane 1, the
    #     scalar lane, holds a nonzero step cap (0x1FF, rs1[7:0] = 255); a cap
    #     read per lane or from lane 0 is 0, so active lanes would keep canaries.
    #   Pass 2, M = 0x55: lanes 0, 2, 4, 6 trace into s7..s9. Their rays were
    #     inactive in pass 1, so they hit as expected only if pass 1 left their
    #     ray state unchanged.
    .insn r 0x0B, 7, 0, x0, x0, x0          # MASKALL
    .insn r 0x0B, 0, 0, a0, x0, x0          # LANEID a0 (0..7)

    # a2 = &vtrace_vectors[lane + 8]
    addi    a3, a0, 8
    slli    a1, a3, 5                       # vector_idx * 32
    slli    a2, a3, 4                       # vector_idx * 16
    add     a1, a1, a2                      # vector_idx * 48
    la      a2, vtrace_vectors
    add     a2, a2, a1

    # Per-lane VSET 0..7 in all lanes
    lw      t0, 0(a2)
    .insn r 0x2B, 0, 0, x0, t0, x0          # VSET 0
    lw      t0, 4(a2)
    .insn r 0x2B, 0, 1, x0, t0, x0          # VSET 1
    lw      t0, 8(a2)
    .insn r 0x2B, 0, 2, x0, t0, x0          # VSET 2
    lw      t0, 12(a2)
    .insn r 0x2B, 0, 3, x0, t0, x0          # VSET 3
    lw      t0, 16(a2)
    .insn r 0x2B, 0, 4, x0, t0, x0          # VSET 4
    lw      t0, 20(a2)
    .insn r 0x2B, 0, 5, x0, t0, x0          # VSET 5
    lw      t0, 24(a2)
    .insn r 0x2B, 0, 6, x0, t0, x0          # VSET 6
    lw      t0, 28(a2)
    .insn r 0x2B, 0, 7, x0, t0, x0          # VSET 7

    # a1 = 0x1FF in lane 1, 0 in every other lane (branch-free)
    addi    t0, a0, -1
    seqz    t0, t0
    neg     t0, t0
    li      t1, 0x1FF
    and     a1, t0, t1

    # Canaries in every lane's destination registers
    li      s6, 0xCAFEBABE
    mv      a4, s6
    mv      a5, s6
    mv      a6, s6
    mv      s7, s6
    mv      s8, s6
    mv      s9, s6

    # Pass 1: M = 0xAA, scalar lane 1
    li      t0, 0xAA
    .insn r 0x0B, 6, 0, x0, t0, x0          # MASKSET 0xAA
    .insn r 0x2B, 1, 0, a4, a1, x0          # VTRACE a4, a1
    .insn r 0x2B, 2, 0, a5, x0, x0          # VGET a5, 0 (cell)
    .insn r 0x2B, 2, 1, a6, x0, x0          # VGET a6, 1 (t)

    # Pass 2: M = 0x55, scalar lane 0
    .insn r 0x0B, 7, 0, x0, x0, x0          # MASKALL
    li      a1, 0xFF
    li      t0, 0x55
    .insn r 0x0B, 6, 0, x0, t0, x0          # MASKSET 0x55
    .insn r 0x2B, 1, 0, s7, a1, x0          # VTRACE s7, a1
    .insn r 0x2B, 2, 0, s8, x0, x0          # VGET s8, 0 (cell)
    .insn r 0x2B, 2, 1, s9, x0, x0          # VGET s9, 1 (t)

    # Store every lane's registers, active or not
    .insn r 0x0B, 7, 0, x0, x0, x0          # MASKALL
    slli    t1, a0, 2
    la      t0, lane_out
    add     t0, t0, t1
    sw      a4, 0(t0)
    sw      a5, 32(t0)
    sw      a6, 64(t0)
    sw      s7, 96(t0)
    sw      s8, 128(t0)
    sw      s9, 160(t0)

    # 6. No-write cases (Tai_2 §2, VTRACE row): a cap of 0, a cap of 256
    # (rs1[7:0] = 0) and M = 0 finish with rd and the VGET results unchanged.
    # Checked in all lanes under MASKALL; BALLOT gathers the mismatching lanes.
    .macro NO_WRITE number
    .insn r 0x2B, 2, 0, a5, x0, x0          # VGET a5, 0
    .insn r 0x2B, 2, 1, a6, x0, x0          # VGET a6, 1
    xor     t0, a4, s6
    xor     t1, a5, s10
    or      t0, t0, t1
    xor     t1, a6, s11
    or      t0, t0, t1
    .insn r 0x0B, 3, 0, t0, t0, x0          # BALLOT t0, t0 (same in every lane)
    EXPECT_REG t0, zero, \number
    .endm

    .insn r 0x2B, 2, 0, s10, x0, x0         # VGET s10, 0 (baseline)
    .insn r 0x2B, 2, 1, s11, x0, x0         # VGET s11, 1 (baseline)
    mv      a4, s6

    li      a1, 0
    .insn r 0x2B, 1, 0, a4, a1, x0          # VTRACE a4, cap 0
    NO_WRITE 160

    li      a1, 0x100
    .insn r 0x2B, 1, 0, a4, a1, x0          # VTRACE a4, cap 256 -> rs1[7:0] = 0
    NO_WRITE 161

    li      a1, 0xFF
    .insn r 0x0B, 6, 0, x0, x0, x0          # MASKSET x0 -> M = 0
    .insn r 0x2B, 1, 0, a4, a1, x0          # VTRACE a4, a1 with M = 0
    .insn r 0x0B, 7, 0, x0, x0, x0          # MASKALL
    NO_WRITE 162

    # Return to scalar mask 1 and validate the stored lanes
    SCALAR

    # Active lane: low 16 bits of res, cell and t match vector lane + 8.
    # Inactive lane: all three registers still hold the canary.
    .macro LANE_CHECK pass, lane, active
    la      t0, lane_out + (\pass - 1) * 96 + \lane * 4
    li      t1, 48 * (\lane + 8)
    add     t1, s3, t1                      # &vtrace_vectors[lane + 8]
    lw      a0, 0(t0)                       # res
    lw      t3, 32(t0)                      # cell
    lw      t4, 64(t0)                      # t
    .if \active
    slli    a0, a0, 16
    srli    a0, a0, 16
    lw      t2, 36(t1)
    slli    t2, t2, 16
    srli    t2, t2, 16
    EXPECT_REG a0, t2, 100 + (\pass - 1) * 30 + \lane
    lw      t2, 40(t1)
    EXPECT_REG t3, t2, 110 + (\pass - 1) * 30 + \lane
    lw      t2, 44(t1)
    EXPECT_REG t4, t2, 120 + (\pass - 1) * 30 + \lane
    .else
    EXPECT_REG a0, s6, 100 + (\pass - 1) * 30 + \lane
    EXPECT_REG t3, s6, 110 + (\pass - 1) * 30 + \lane
    EXPECT_REG t4, s6, 120 + (\pass - 1) * 30 + \lane
    .endif
    .endm

    la      s3, vtrace_vectors
    LANE_CHECK 1, 0, 0
    LANE_CHECK 1, 1, 1
    LANE_CHECK 1, 2, 0
    LANE_CHECK 1, 3, 1
    LANE_CHECK 1, 4, 0
    LANE_CHECK 1, 5, 1
    LANE_CHECK 1, 6, 0
    LANE_CHECK 1, 7, 1
    LANE_CHECK 2, 0, 1
    LANE_CHECK 2, 1, 0
    LANE_CHECK 2, 2, 1
    LANE_CHECK 2, 3, 0
    LANE_CHECK 2, 4, 1
    LANE_CHECK 2, 5, 0
    LANE_CHECK 2, 6, 1
    LANE_CHECK 2, 7, 0
#endif

    # All tests passed!
    PASS

    # Include expected reference vectors and sparse world data generated from C reference
    .include "sw/tests/t_vtrace_expected.inc"

    .section .bss
    .balign 4
# 2 passes x {res, cell, t} x 8 lanes
lane_out:
    .space 192
