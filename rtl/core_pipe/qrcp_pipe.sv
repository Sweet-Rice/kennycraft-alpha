// Pipelined QRCP unit of the pipelined core, one per lane: y = the Q16.16
// reciprocal of x, bit-exact with rtl/core/qrcp.sv and so with qrcp() in
// game/src/fixed.c (normative). The steps and truncations are qrcp.sv's,
// spread over seven register stages so that every register-to-register
// segment of the 100 MHz core clock stays well below 10 ns; MEM holds a
// QRCP for eight cycles:
//
//   MEM cycle 0 (s0)  from x (lane_pipe's res, a register): n = leading
//                     zeros of x | 2; xc = x << 8 n[4:3] (the coarse part
//                     of the normalizing shift), n[2:0], sh = 30 - n and
//                     lt4 = x < 4 (signed) are registered
//   MEM cycle 1       m = (xc << n[2:0])[31:15] (= (x << n)[31:15]) and
//                     r = SEED[m[15:8]] are registered
//   MEM cycle 2       p1 = m * r into the multiplier's output register
//                     (DSP48E1 MREG)
//   MEM cycle 3       f = 2^17 - p1[32:16] is registered
//   MEM cycle 4       p2 = f * r into the second multiplier's MREG
//   MEM cycle 5       v = shift back of p2[33:16] by sh, registered
//   MEM cycle 6       y = v saturated at Q16_BIG (Q16_BIG when lt4)
//   MEM cycle 7       y is valid: MEM's result for forwarding and WB
//
// Only the cycle-0 registers have an enable (s0): x need be valid only
// then. Every later stage loads each cycle from the stage before; as the
// cycle-0 registers hold, the stages settle and y stays valid until the
// next s0. Every path starts at a register and ends at one, so lane_pipe's
// MEM -> EX forward still sees only the y register. The two products use
// one multiplier each (17 x 16 and 18 x 16 bits unsigned); their outputs go
// combinationally (no PREG) into the short stage after them. SEED is
// qrcp.sv's ROM, generated by the same function.
module qrcp_pipe (
    input  logic        clk,
    input  logic        s0,       // MEM cycle 0 of a QRCP: x is valid
    input  logic [31:0] x,        // rs1
    output logic [31:0] y
);

    localparam int K0 = 92000;    // KC_RCP_K0
    localparam int K1 = 60;       // KC_RCP_K1
    localparam int N1 = 8;        // KC_RCP_N1
    localparam int N2 = 3;        // KC_RCP_N2
    localparam logic [31:0] Q16_BIG = 32'h4000_0000;

    function automatic logic [15:0] seed_of(input int i);
        int d, yy, e;
        d  = 2 * (256 + i) + 1;
        yy = K0 - K1 * d;
        e  = (1 << 25) - d * yy;  yy += (yy * (e >>> N1)) >>> (25 - N1);
        e  = (1 << 25) - d * yy;  yy += (yy * (e >>> N2)) >>> (25 - N2);
        return 16'(yy + ((unsigned'(d * (2 * yy + 1)) < 32'd67108864) ? 1 : 0));
    endfunction

    logic [15:0] seed_rom [256];
    for (genvar i = 0; i < 256; i++) begin : g_seed
        localparam logic [15:0] V = seed_of(i);
        assign seed_rom[i] = V;
    end

    // MEM cycle 0: leading zeros and the coarse shift
    logic [31:0] xo, xc0;
    logic [4:0]  n;

    assign xo = x | 32'd2;
    always_comb begin
        n = 5'd30;
        for (int i = 1; i < 32; i++)
            if (xo[i]) n = 5'(31 - i);
    end
    assign xc0 = x << {n[4:3], 3'b000};

    logic [31:8] xc;              // xc0[7:0] never reach m (n[2:0] <= 7)
    logic [2:0]  nf;
    logic [4:0]  sh;
    logic        lt4;

    always_ff @(posedge clk) begin
        if (s0) begin
            xc  <= xc0[31:8];
            nf  <= n[2:0];
            sh  <= 5'd30 - n;
            lt4 <= $signed(x) < 32'sd4;
        end
    end

    // MEM cycle 1: fine shift and seed ROM
    logic [31:8] xn;
    logic [16:0] m0, m;
    logic [15:0] r;

    assign xn = xc << nf;
    assign m0 = xn[31:15];

    always_ff @(posedge clk) begin
        m <= m0;
        r <= seed_rom[m0[15:8]];
    end

    // MEM cycles 2 to 6: first product, f, second product, shift back,
    // saturate (qrcp.sv's ph 0, 1 and 2)
    logic [32:0] p1;
    logic [17:0] f;
    logic [33:0] p2;
    logic [46:0] wide;
    logic [31:0] v;

    assign wide = {14'd0, p2[33:16], 15'd0} >> sh;

    always_ff @(posedge clk) begin
        p1 <= 33'(m) * 33'(r);
        f  <= 18'h2_0000 - {1'b0, p1[32:16]};
        p2 <= 34'(f) * 34'(r);
        v  <= wide[31:0];
        y  <= (lt4 || $signed(v) > $signed(Q16_BIG)) ? Q16_BIG : v;
    end

    // xn[14:8] are below the 17 bits fixed.c keeps, p1[15:0] and p2[15:0]
    // below both results, and wide[46:32] is what the C's 32-bit left shift
    // drops.
    /* verilator lint_off UNUSEDSIGNAL */
    logic unused;
    assign unused = ^{xc0[7:0], xn[14:8], p1[15:0], p2[15:0], wide[46:32]};
    /* verilator lint_on UNUSEDSIGNAL */

endmodule
