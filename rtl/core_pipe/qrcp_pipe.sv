// Two-step QRCP unit of the pipelined core, one per lane: y = the Q16.16
// reciprocal of x, bit-exact with rtl/core/qrcp.sv and so with qrcp() in
// game/src/fixed.c (normative). The steps and truncations are qrcp.sv's,
// regrouped so that MEM holds a QRCP for three cycles instead of five:
//
//   s0 (MEM cycle 0)  from x (lane_pipe's res, a register): n = leading
//                     zeros of x | 2, m = (x << n)[31:15], r = SEED[m[15:8]],
//                     p1 = m * r, f = 2^17 - p1[32:16]; f, r, sh = 30 - n
//                     and lt4 = x < 4 (signed) are registered
//   s1 (MEM cycle 1)  p2 = f * r, shifted back by sh and saturated at
//                     Q16_BIG (Q16_BIG when lt4), registered into y
//   MEM cycle 2       y is valid: MEM's result for forwarding and WB
//
// Every path starts at a register (x or the s0 registers) and ends at one,
// so lane_pipe's MEM -> EX forward still sees only the y register. The two
// products use one multiplier each (17 x 16 and 18 x 16 bits unsigned).
// SEED is qrcp.sv's ROM, generated by the same function.
module qrcp_pipe (
    input  logic        clk,
    input  logic        s0,       // MEM cycle 0 of a QRCP: x is valid
    input  logic        s1,       // MEM cycle 1
    input  logic [31:0] x,        // rs1
    output logic [31:0] y
);

    localparam int K0 = 92000;    // KC_RCP_K0
    localparam int K1 = 60;       // KC_RCP_K1
    localparam int N1 = 8;        // KC_RCP_N1
    localparam int N2 = 3;        // KC_RCP_N2
    localparam logic [31:0] Q16_BIG = 32'h4000_0000;

    function automatic logic [15:0] seed_of(input int i);
        int d, yy, e;
        d  = 2 * (256 + i) + 1;
        yy = K0 - K1 * d;
        e  = (1 << 25) - d * yy;  yy += (yy * (e >>> N1)) >>> (25 - N1);
        e  = (1 << 25) - d * yy;  yy += (yy * (e >>> N2)) >>> (25 - N2);
        return 16'(yy + ((unsigned'(d * (2 * yy + 1)) < 32'd67108864) ? 1 : 0));
    endfunction

    logic [15:0] seed_rom [256];
    for (genvar i = 0; i < 256; i++) begin : g_seed
        localparam logic [15:0] V = seed_of(i);
        assign seed_rom[i] = V;
    end

    // s0: norm_shift, seed, first product
    logic [31:0] xo, xn;
    logic [4:0]  n;
    logic [16:0] m;
    logic [15:0] r0;
    logic [32:0] p1;

    assign xo = x | 32'd2;
    always_comb begin
        n = 5'd30;
        for (int i = 1; i < 32; i++)
            if (xo[i]) n = 5'(31 - i);
    end
    assign xn = x << n;
    assign m  = xn[31:15];
    assign r0 = seed_rom[m[15:8]];
    assign p1 = 33'(m) * 33'(r0);

    logic [17:0] f;
    logic [15:0] r;
    logic [4:0]  sh;
    logic        lt4;

    always_ff @(posedge clk) begin
        if (s0) begin
            f   <= 18'h2_0000 - {1'b0, p1[32:16]};
            r   <= r0;
            sh  <= 5'd30 - n;
            lt4 <= $signed(x) < 32'sd4;
        end
    end

    // s1: second product, shift back and saturate (qrcp.sv's ph 1 and 2)
    logic [33:0] p2;
    logic [46:0] wide;
    logic [31:0] v;

    assign p2   = 34'(f) * 34'(r);
    assign wide = {14'd0, p2[33:16], 15'd0} >> sh;
    assign v    = wide[31:0];

    always_ff @(posedge clk)
        if (s1) y <= (lt4 || $signed(v) > $signed(Q16_BIG)) ? Q16_BIG : v;

    // xn[14:0] are below the 17 bits fixed.c keeps, p1[15:0] and p2[15:0]
    // below both results, and wide[46:32] is what the C's 32-bit left shift
    // drops.
    /* verilator lint_off UNUSEDSIGNAL */
    logic unused;
    assign unused = ^{xn[14:0], p1[15:0], p2[15:0], wide[46:32]};
    /* verilator lint_on UNUSEDSIGNAL */

endmodule
